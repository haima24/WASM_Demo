// Web Worker that runs the Rust code (compiled to WebAssembly).
//
// Why a worker: heavy work here would freeze the page. A worker runs on its own thread.
// The page talks to it with messages: see `Remote` in `lib/engines.ts` for the sending side.
//
// Messages in (all carry an `id` that is echoed back in the reply):
//   { kind: 'ping' }                                       -> { initMs }
//   { kind: 'image', pixels, width, height, filter }       -> { processingMs, memoryBytes, pixels }
//   { kind: 'csv' | 'xlsx', bytes }                        -> { processingMs, memoryBytes, report }
//   any failure                                            -> { error }

// `src/wasm/` is generated by `npm run build:wasm` (wasm-pack) from the Rust crate in `rust-core/`.
// These three functions are the `#[wasm_bindgen]` functions in `rust-core/src/lib.rs`.
import init, { apply_filter, validate_csv, validate_xlsx } from '../wasm/rust_core.js';

const ctx = self as any;

let wasmMemory: WebAssembly.Memory | undefined;
let initMs = 0; // one-time download + compile + instantiate time, reported separately from the runs

// Start loading the .wasm file right away; every message waits for this before doing work.
const ready = (async () => {
  const start = performance.now();
  const wasm = await init();
  wasmMemory = wasm.memory;
  initMs = performance.now() - start;
})();

ctx.onmessage = async (event: MessageEvent) => {
  const msg = event.data;
  try {
    await ready;

    if (msg.kind === 'ping') {
      ctx.postMessage({ id: msg.id, initMs });
      return;
    }

    // The timed region includes copying the input into WASM memory and the result back out:
    // that JS <-> WASM boundary cost is real, so it is part of the measurement.
    const start = performance.now();
    const memoryBytes = () => wasmMemory?.buffer.byteLength;

    if (msg.kind === 'image') {
      const pixels = apply_filter(new Uint8Array(msg.pixels), msg.width, msg.height, msg.filter);
      const processingMs = performance.now() - start;
      // List `pixels.buffer` as transferable so it moves to the page instead of being copied.
      ctx.postMessage({ id: msg.id, processingMs, memoryBytes: memoryBytes(), pixels: pixels.buffer }, [pixels.buffer]);
    } else {
      // The Rust validators return the report as a JSON string; parsing it is part of the timed work.
      const validate = msg.kind === 'csv' ? validate_csv : validate_xlsx;
      const report = JSON.parse(validate(new Uint8Array(msg.bytes)));
      const processingMs = performance.now() - start;
      ctx.postMessage({ id: msg.id, processingMs, memoryBytes: memoryBytes(), report });
    }
  } catch (err) {
    ctx.postMessage({ id: msg.id, error: String(err) });
  }
};
